// Derive lightweight display modules from the approved embedded source masters.
// Downloads embed these same resources on demand; artwork itself is unchanged.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const source=await readFile('lib/kolase-source-assets.ts','utf8');
const assets=JSON.parse(source.match(/export const kolaseSourceAssets = (.*);/)[1]);
const font=JSON.parse(source.match(/export const kolaseSourceFont = (.*);/)[1]);
const runtime={};
let template=await readFile('lib/kolase-landscape-template.ts','utf8');
await mkdir('public/art/kolase-display',{recursive:true});
for(const [key,value] of Object.entries(assets)){
 const actual=Buffer.from(value.split(',')[1],'base64');
 const hash=createHash('sha256').update(actual).digest('hex').slice(0,12);
 const url=`/art/kolase-display/${key}-${hash}.png`;
 await writeFile(`public${url}`,actual);
 runtime[key]=url;
 template=template.split(value).join(url);
}
const fontUrl='/fonts/nordestino-reconstructed-regular.ttf';
if(!(await readFile(`public${fontUrl}`)).equals(Buffer.from(font,'base64')))throw Error('Font mismatch');
template=template.split(`data:font/ttf;base64,${font}`).join(fontUrl);
if(template.includes('base64,'))throw Error('Unmapped embedded artwork in landscape');
await writeFile('lib/kolase-display-assets.ts',`// Generated by scripts/externalize-kolase.mjs; immutable source pixels verified.\nexport const kolaseSourceAssets = ${JSON.stringify(runtime,null,2)} as const;\nexport const kolaseSourceFont = ${JSON.stringify(fontUrl)};\n`);
await writeFile('lib/kolase-display-template.ts',`// Generated by scripts/externalize-kolase.mjs.\n${template}`);
console.log('Externalized approved Kolase display assets; embedded source masters retained for provenance.');

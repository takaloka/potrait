import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const moduleUrl = source => `data:text/javascript;base64,${Buffer.from(ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText).toString('base64')}`;
const connectionUrl = moduleUrl(await readFile(new URL('../lib/chatgpt-connection.ts',import.meta.url),'utf8'));
const {ChatgptError} = await import(connectionUrl);
globalThis.__callbackError = new ChatgptError('Browser callback ChatGPT tidak cocok.');
const serverUrl = moduleUrl('export function chatgptConnection(){ return { complete: async()=>{ throw globalThis.__callbackError; } }; }');
const source=(await readFile(new URL('../app/auth/callback/route.ts',import.meta.url),'utf8')).replace('"@/lib/photobooth-server"',JSON.stringify(serverUrl)).replace('"@/lib/chatgpt-connection"',JSON.stringify(connectionUrl));
const route=await import(moduleUrl(source));
const request=new Request('http://127.0.0.1:8787/auth/callback?code=secret-code&error_description=secret-detail');
const response=await route.GET(request);
assert.equal(response.status,303);
const redirect = new URL(response.headers.get('location'),'http://127.0.0.1:8787');
assert.equal(redirect.searchParams.get('reason'),'Browser callback ChatGPT tidak cocok.','surface safe cause rather than generic failure');
assert.doesNotMatch(response.headers.get('location'),/secret-/);
globalThis.__callbackError=new Error('token=secret-internal');
const failed=await route.GET(request);
assert.doesNotMatch(failed.headers.get('location'),/secret-internal/);
assert.equal(failed.headers.get('cache-control'),'no-store');
console.log('PASS callback: safe actionable error retained; raw provider and internal secrets omitted.');

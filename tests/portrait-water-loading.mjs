import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const moduleUrl=source=>`data:text/javascript;base64,${Buffer.from(ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022,jsx:ts.JsxEmit.ReactJSX}}).outputText.replaceAll('"react/jsx-runtime"',JSON.stringify(import.meta.resolve('react/jsx-runtime'))).replaceAll('"react"',JSON.stringify(import.meta.resolve('react')))).toString('base64')}`;
const artUrl=moduleUrl(await readFile(new URL('../lib/nusantara-art.ts',import.meta.url),'utf8'));
const {nusantaraSvg}=await import(artUrl);
const loading=nusantaraSvg({name:'Test',image:'/private-original.png',portraitLoading:true,id:'fixture'});
assert.doesNotMatch(loading,/private-original/,'loading must never embed original photo');
assert.equal((loading.match(/class="portrait-water-flow"/g)||[]).length,1,'one clipped central water layer');
assert.match(loading,/<svg[^>]+overflow="hidden">[\s\S]*portrait-water-flow/);
assert.equal((loading.match(/\/art\/nusantara\/window.png/g)||[]).length,3,'preserve all three windows');
const ready=nusantaraSvg({name:'Test',image:'/generated.png',portraitReveal:true});
assert.match(ready,/class="portrait-image-reveal"/);assert.match(ready,/generated.png/);assert.doesNotMatch(ready,/portrait-water-flow/);
const exported=nusantaraSvg({name:'Test',image:'/generated.png'});
assert.doesNotMatch(exported,/portrait-image-reveal|portrait-water-flow/,'static exports stay static');
const sourceAssetsUrl=moduleUrl(await readFile(new URL('../lib/kolase-display-assets.ts',import.meta.url),'utf8'));
const kolaseUrl=moduleUrl((await readFile(new URL('../lib/kolase-art.ts',import.meta.url),'utf8')).replace('"./kolase-display-assets"',JSON.stringify(sourceAssetsUrl)));
const themesUrl=moduleUrl((await readFile(new URL('../lib/poster-themes.ts',import.meta.url),'utf8')).replace('"./nusantara-art"',JSON.stringify(artUrl)).replace('"./kolase-art"',JSON.stringify(kolaseUrl)));
const {posterSvg}=await import(themesUrl);
for(const theme of ['nusantara','kolase']) {
  const pending=posterSvg({theme,name:'<script>Test</script>',image:'/private-original.png',portraitLoading:true});
  assert.doesNotMatch(pending,/<script>|private-original/);
  assert.match(pending,/portrait-water-flow/);
  const screen=posterSvg({theme,name:'',image:'',landscape:true,liveSlots:true});
  assert.equal((screen.match(/data-portrait-slot=/g)||[]).length,1);
  assert.equal((screen.match(/data-portrait-name=/g)||[]).length,1);
  const result=posterSvg({theme,name:'Test',image:'/generated.png',portraitReveal:true});
  assert.match(result,/portrait-image-reveal/);
}
assert.equal(posterSvg({name:'Old',image:''}),nusantaraSvg({name:'Old',image:''}),'old posters retain exact artwork');
const posterUrl=moduleUrl((await readFile(new URL('../components/football-poster.tsx',import.meta.url),'utf8')).replace('"@/lib/poster-themes"',JSON.stringify(themesUrl)));
const {FootballPoster}=await import(posterUrl);
const poster=renderToStaticMarkup(React.createElement(FootballPoster,{name:'Test',image:'/not-yet-decoded.png',reveal:true}));
assert.doesNotMatch(poster,/not-yet-decoded.png/,'do not show AI image until decoding succeeds');
assert.match(poster,/portrait-water-flow/);
const source=await readFile(new URL('../components/participant-result.tsx',import.meta.url),'utf8');
assert.doesNotMatch(source,/image=\{job.resultUrl \|\| job.originalUrl\}/,'participant never falls back to original');
console.log('PASS portrait water loading: hidden original, central-only clipped waves, preserved geometry, decode gate and static export compatibility.');
